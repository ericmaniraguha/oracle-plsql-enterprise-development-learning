-- ============================================================================================
-- EMPLOYEE AUDIT APPLICATION
-- This script sets up auditing for the EMPLOYEES table.
-- It tracks INSERT, UPDATE, DELETE operations including user info and client IP.
-- Questions are embedded to help understand each step.
--
-- CHANGES:
-- - One INSERT in the trigger instead of three near-identical copies.
-- - Test uses a new employee ID (999). Employee 101 already exists, so the
--   old INSERT failed and the DELETE targeted a real employee.
-- - Step 0 removes leftover audit triggers from the other lessons.
-- - User-name columns are VARCHAR2(128); the demo ends with ROLLBACK.
-- ============================================================================================

-- ============================================================================================
-- 0. Remove audit triggers left by the other lessons in this folder
-- Q: Why?
-- A: Lessons 04-07 each re-create EMPLOYEES_AUDIT with different columns. A trigger
--    from an earlier lesson becomes INVALID when the table changes, and then EVERY
--    INSERT/UPDATE/DELETE on EMPLOYEES fails with ORA-04098.
BEGIN
    FOR t IN (
        SELECT trigger_name
        FROM user_triggers
        WHERE trigger_name IN ('EMP_AUDIT_TRG', 'EMP_AUDIT_TRIGGER', 'EMP_AUDIT_TAX_TRIGGER')
    ) LOOP
        -- Q: Why DBMS_ASSERT.ENQUOTE_NAME?
        -- A: It safely quotes an object name before it is glued into dynamic SQL.
        EXECUTE IMMEDIATE 'DROP TRIGGER ' || DBMS_ASSERT.ENQUOTE_NAME(t.trigger_name);
    END LOOP;
END;
/

-- ============================================================================================
-- 1. Drop the audit table if it already exists
-- Q: Why do we drop the table first?
-- A: To make sure we can rerun the script without errors.
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE employees_audit CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        -- Q: What does SQLCODE -942 mean?
        -- A: Table does not exist. We ignore this error.
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/
-- ============================================================================================

-- ============================================================================================
-- 2. Create a function to get the client IP address
-- Q: Why do we need a function for client info?
-- A: So the trigger can record which computer or user session performed the operation.
CREATE OR REPLACE FUNCTION get_client_info
RETURN VARCHAR2
IS
BEGIN
    RETURN SYS_CONTEXT('USERENV','IP_ADDRESS');
END;
/
-- Q: How do we test the function?
SELECT get_client_info() AS client_ip FROM dual;
-- ============================================================================================

-- ============================================================================================
-- 3. Create the audit table
-- Q: What columns do we need for auditing?
-- A: We need operation type, timestamp, affected table, number of rows, DB user, OS user, client IP, session ID.
CREATE TABLE employees_audit (
    audit_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- Unique ID for each audit record
    action_type    VARCHAR2(20),   -- INSERT, UPDATE, DELETE
    action_date    DATE,           -- When the action occurred
    affected_table VARCHAR2(128),  -- Table affected (EMPLOYEES)
    total_rows     NUMBER,         -- How many rows affected (default 1 for row-level)
    db_user        VARCHAR2(128),  -- DB user performing the action (names can be up to 128 chars)
    os_user        VARCHAR2(128),  -- OS user (e.g. DOMAIN\user can be long)
    client_ip      VARCHAR2(50),   -- Client IP
    session_id     VARCHAR2(50)    -- Session ID for traceability
);
-- ============================================================================================

-- ============================================================================================
-- 4. Create a trigger to audit all DML operations on EMPLOYEES
-- Q: Why do we use a single trigger for INSERT, UPDATE, DELETE?
-- A: It simplifies management and ensures all changes are logged consistently.
CREATE OR REPLACE TRIGGER emp_audit_trigger
AFTER INSERT OR UPDATE OR DELETE ON employees
FOR EACH ROW
DECLARE
    v_action employees_audit.action_type%TYPE;
BEGIN
    -- Q: How does the trigger know which operation fired it?
    -- A: The PL/SQL predicates INSERTING, UPDATING and DELETING.
    v_action := CASE
                    WHEN INSERTING THEN 'INSERT'
                    WHEN UPDATING  THEN 'UPDATE'
                    ELSE                'DELETE'
                END;

    -- Q: What info are we logging?
    -- A: Action type, timestamp, table, user, OS user, client IP, session.
    --    The same INSERT serves all three operations; only v_action differs.
    INSERT INTO employees_audit (
        action_type, action_date, affected_table, total_rows,
        db_user, os_user, client_ip, session_id
    ) VALUES (
        v_action, SYSDATE, 'EMPLOYEES', 1,
        SYS_CONTEXT('USERENV','SESSION_USER'),
        SYS_CONTEXT('USERENV','OS_USER'),
        get_client_info(),
        SYS_CONTEXT('USERENV','SESSIONID')
    );
END;
/
-- ============================================================================================

-- ============================================================================================
-- 5. Test the audit trigger
-- Q: Why do we test all three operations?
-- A: To ensure the trigger correctly logs INSERT, UPDATE, and DELETE actions.

-- INSERT test (999 is a new, unused employee ID)
INSERT INTO employees (
    employee_id, first_name, last_name, email,
    phone_number, hire_date, job_id, salary, department_id
) VALUES (
    999, 'Alice', 'MUSAYIDIRE', 'alice@example.com',
    '0788746969', SYSDATE, 'IT_PROG', 5000, 10
);

-- UPDATE test (department 10 now has 2 employees)
UPDATE employees
SET salary = salary + 500
WHERE department_id = 10;

-- DELETE test
DELETE FROM employees
WHERE employee_id = 999;

-- Check audit log
SELECT * FROM employees_audit ORDER BY audit_id;

-- Q: What should we see in the audit table?
-- A: Four rows: 1 INSERT, 2 UPDATEs (one per employee in department 10,
--    because this is a ROW-level trigger), and 1 DELETE, with user, IP and
--    session info.

-- Demo only: undo the test changes (and their audit rows). Use COMMIT to keep them.
ROLLBACK;
