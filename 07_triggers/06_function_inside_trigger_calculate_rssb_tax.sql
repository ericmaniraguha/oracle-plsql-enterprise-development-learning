-- ============================================================================================
-- EMPLOYEE AUDIT & TAX APPLICATION
-- This script tracks all DML operations on EMPLOYEES
-- and automatically calculates RSSB tax (5% of salary).
-- All steps, functions, and triggers are in a single editor.
-- Questions are embedded for learning purposes.
--
-- CHANGES:
-- - Re-runnable: "ALTER TABLE employees ADD (rssb_tax ...)" failed with ORA-01430
--   on the second run; it is now skipped when the column exists.
-- - The tax is recalculated only when SALARY changes (UPDATING('SALARY')),
--   not on every update of any column.
-- - One audit INSERT instead of three near-identical copies.
-- - calc_rssb_tax is DETERMINISTIC.
-- - Test uses a new employee ID (999). Employee 101 already exists, so the old
--   INSERT failed and the DELETE targeted a real employee. Ends with ROLLBACK.
-- - Step 0 removes leftover audit triggers of the other lessons (they become
--   INVALID when EMPLOYEES_AUDIT is re-created and then all DML fails, ORA-04098).
-- ============================================================================================

-- 0. Remove audit triggers left by the other lessons in this folder
BEGIN
    FOR t IN (
        SELECT trigger_name
        FROM user_triggers
        WHERE trigger_name IN ('EMP_AUDIT_TRG', 'EMP_AUDIT_TRIGGER', 'EMP_AUDIT_TAX_TRIGGER')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TRIGGER ' || DBMS_ASSERT.ENQUOTE_NAME(t.trigger_name);
    END LOOP;
END;
/

-- 1. Drop audit table if exists
-- Q: Why drop the table first?
-- A: To avoid errors if the script is rerun.
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE employees_audit CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN -- Table does not exist
            RAISE;
        END IF;
END;
/

-- 2. Create function to get client IP
-- Q: Why use a function for client IP?
-- A: So triggers can easily capture which client/session performed the operation.
CREATE OR REPLACE FUNCTION get_client_info
RETURN VARCHAR2
IS
BEGIN
    RETURN SYS_CONTEXT('USERENV','IP_ADDRESS');
END;
/
-- Test function
SELECT get_client_info() AS client_ip FROM dual;

-- 3. Create function to calculate RSSB tax
-- Q: Why a separate function?
-- A: Makes tax calculation reusable in triggers, reports, or procedures.
-- Q: Why DETERMINISTIC?
-- A: The result depends only on the salary, so Oracle may cache it in SQL.
CREATE OR REPLACE FUNCTION calc_rssb_tax(p_salary IN NUMBER)
RETURN NUMBER
DETERMINISTIC
IS
BEGIN
    RETURN p_salary * 0.05; -- Example: RSSB = 5% of salary
END;
/
-- Test function
SELECT calc_rssb_tax(5000) AS rssb_tax FROM dual;

-- 4. Create audit table
-- Q: What columns are required for auditing?
-- A: Operation type, timestamp, affected table, row info, user, OS, IP, session.
CREATE TABLE employees_audit (
    audit_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type    VARCHAR2(20),
    action_date    DATE,
    affected_table VARCHAR2(128),
    total_rows     NUMBER,
    db_user        VARCHAR2(128),
    os_user        VARCHAR2(128),
    client_ip      VARCHAR2(50),
    session_id     VARCHAR2(50)
);

-- 5. Alter employees table to add RSSB tax column (only if it is missing)
-- Q: Why add rssb_tax column?
-- A: So we store calculated tax for each employee.
-- Q: Is a trigger the only way?
-- A: No. A VIRTUAL column is simpler when the value is a pure formula:
--      ALTER TABLE employees ADD (rssb_tax AS (salary * 0.05));
--    Oracle computes it on read: no trigger, no extra storage, never stale.
--    This lesson uses a trigger to practise calling a function from a trigger.
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE employees ADD (rssb_tax NUMBER(8,2))';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN   -- -1430 = column already exists
            RAISE;
        END IF;
END;
/

-- 6. Create trigger for auditing + tax calculation
-- Q: Why combine audit + tax in one trigger?
-- A: Ensures every DML logs changes and automatically calculates RSSB tax.
CREATE OR REPLACE TRIGGER emp_audit_tax_trigger
BEFORE INSERT OR UPDATE OR DELETE ON employees
FOR EACH ROW
DECLARE
    v_action employees_audit.action_type%TYPE;
BEGIN
    -- ---------- RSSB TAX CALCULATION ----------
    -- Only when a row is inserted or its SALARY changes. UPDATING('SALARY') is
    -- TRUE only if the UPDATE's SET clause includes SALARY, so updates of other
    -- columns skip the function call.
    IF INSERTING OR UPDATING('SALARY') THEN
        :NEW.rssb_tax := calc_rssb_tax(:NEW.salary);
        -- Q: Why BEFORE trigger for tax?
        -- A: So rssb_tax is updated in the row before it is saved.
    END IF;

    -- ---------- AUDIT LOG ----------
    v_action := CASE
                    WHEN INSERTING THEN 'INSERT'
                    WHEN UPDATING  THEN 'UPDATE'
                    ELSE                'DELETE'
                END;

    INSERT INTO employees_audit (
        action_type, action_date, affected_table, total_rows,
        db_user, os_user, client_ip, session_id
    ) VALUES (
        v_action, SYSDATE, 'EMPLOYEES', 1,
        SYS_CONTEXT('USERENV','SESSION_USER'),
        SYS_CONTEXT('USERENV','OS_USER'),
        get_client_info(),
        SYS_CONTEXT('USERENV','SESSIONID')
    );
END;
/

-- 7. TEST THE APPLICATION
-- Insert employee (RSSB tax auto-calculated, audit recorded); 999 is unused
INSERT INTO employees (
    employee_id, first_name, last_name, email,
    phone_number, hire_date, job_id, salary, department_id
) VALUES (
    999, 'Alice', 'MUSAYIDIRE', 'alice@example.com',
    '0788746969', SYSDATE, 'IT_PROG', 5000, 10
);

-- Update salary (RSSB tax auto-updated, audit recorded)
UPDATE employees
SET salary = salary + 500
WHERE employee_id = 999;

-- Check RSSB tax calculation BEFORE the delete (should be 5500 * 0.05 = 275)
SELECT employee_id, first_name, salary, rssb_tax
FROM employees
WHERE employee_id = 999;

-- Delete employee (audit recorded)
DELETE FROM employees
WHERE employee_id = 999;

-- Check audit log
SELECT * FROM employees_audit ORDER BY audit_id;

