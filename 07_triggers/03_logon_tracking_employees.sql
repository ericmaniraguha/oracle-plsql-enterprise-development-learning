/*
QUESTION:
-----------
Create a mechanism to log every user login into the database.
For each login, store the following information in a table:

1. A unique log ID
2. Username of the logged-in user
3. The session ID
4. The timestamp of login

You should implement this using a **table** and a **database-level trigger**
that fires **after any user logs on**.

Also, demonstrate how to check that the trigger works by querying the log table.
*/

/*
SOLUTION:
-----------
Step 1: Create the log table
*/
CREATE TABLE USER_LOG (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Unique identifier for each log entry
    USERNAME VARCHAR2(128),                                    -- User names can be up to 128 characters (Oracle 12.2+)
    SESSION_ID NUMBER,                                         -- Tracks the session ID of the user
    LOGON_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL         -- Filled automatically at insert time
);

/*
Step 2: Create a database-level trigger to log user logins

Requires the ADMINISTER DATABASE TRIGGER privilege.

SAFETY NOTE (read this before creating the trigger):
If an AFTER LOGON ON DATABASE trigger raises an error, every user WITHOUT the
ADMINISTER DATABASE TRIGGER privilege is refused at login. A single runtime
failure (for example a full tablespace) would lock the whole class out.
That is why this trigger is the rare place where catching every error is
the right choice: a failed log entry must never block a login.
Everywhere else in this course, unexpected errors are re-raised.

The handler cannot help if the trigger itself becomes INVALID, which happens
when USER_LOG is dropped. Always drop the trigger FIRST:
    DROP TRIGGER trg_logon_audit;
    DROP TABLE user_log;

To limit the trigger to logins of THIS schema only (no special privilege
needed), use "AFTER LOGON ON SCHEMA" instead of "ON DATABASE".
*/
CREATE OR REPLACE TRIGGER trg_logon_audit
AFTER LOGON ON DATABASE
BEGIN
    -- Insert a record into the USER_LOG table for every user logon
    -- (LOGON_TIME comes from the column DEFAULT)
    INSERT INTO USER_LOG (USERNAME, SESSION_ID)
    VALUES (
        SYS_CONTEXT('USERENV', 'SESSION_USER'),   -- Captures the username of the logged-in user
        SYS_CONTEXT('USERENV', 'SESSIONID')       -- Retrieves the current session ID
    );
EXCEPTION
    WHEN OTHERS THEN
        NULL;  -- deliberately ignored: logging must never prevent a login (see note above)
END trg_logon_audit;
/

