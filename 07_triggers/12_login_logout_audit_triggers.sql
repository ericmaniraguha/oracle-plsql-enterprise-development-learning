/* ============================================================
   PRACTICAL QUESTION: DATABASE LOGIN AND LOGOUT AUDITING

   Create an Oracle PL/SQL auditing system to track users' login and
   logout activities.

   Tasks:
   1. Create a table USER_LOGIN_AUDIT to store username, session ID,
      login time, logout time, action type, IP address and hostname.
   2. Create an AFTER LOGON database trigger TRG_USER_LOGIN to record
      user login activities automatically.
   3. Create a BEFORE LOGOFF database trigger TRG_USER_LOGOUT to update
      the corresponding audit record with the logout time.
   4. Use SYS_CONTEXT to capture the database username, session ID,
      IP address and hostname.
   5. Write an SQL query to display all login and logout audit records.
   6. Write a query to check that both triggers were created
      successfully and are enabled.
   ============================================================ */

/* ============================================================
   READ BEFORE RUNNING
   - Run as SYSTEM (or a user with ADMINISTER DATABASE TRIGGER).
   - Both triggers end with  WHEN OTHERS THEN NULL : an error in an
     audit trigger must never stop people from logging in or out.
   - PRAGMA AUTONOMOUS_TRANSACTION + COMMIT makes sure the audit row is
     saved on its own, independently of the user's work.
   - BEFORE LOGOFF fires only on a NORMAL disconnect (EXIT, DISCONNECT,
     closing SQL Developer). A killed session, a crash or a network
     cut leaves LOGOUT_TIME empty - that is expected.
   - IP_ADDRESS is NULL for a local connection (no network listener).
   - Drop order: ALWAYS the triggers first, then the table (Step 8).
   ============================================================ */


/* ============================================================
   STEP 0: CLEAN START
   ============================================================ */
BEGIN
    FOR t IN (SELECT trigger_name FROM user_triggers
              WHERE trigger_name IN ('TRG_USER_LOGIN', 'TRG_USER_LOGOUT')) LOOP
        EXECUTE IMMEDIATE 'DROP TRIGGER ' || DBMS_ASSERT.ENQUOTE_NAME(t.trigger_name);
    END LOOP;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE user_login_audit PURGE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/


/* ============================================================
   STEP 1 (TASK 1): AUDIT TABLE
   ============================================================ */
CREATE TABLE user_login_audit (
    audit_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR2(128),
    session_id   NUMBER,
    login_time   TIMESTAMP,
    logout_time  TIMESTAMP,
    action_type  VARCHAR2(10),          -- 'LOGIN' or 'LOGOUT'
    ip_address   VARCHAR2(50),
    hostname     VARCHAR2(256)
);

-- The logoff trigger searches by session; an index keeps it fast
CREATE INDEX user_login_audit_sess_ix ON user_login_audit (session_id, username);


/* ============================================================
   STEP 2 (TASKS 2 + 4): AFTER LOGON TRIGGER
   ============================================================ */
CREATE OR REPLACE TRIGGER trg_user_login
AFTER LOGON ON DATABASE
DECLARE
    PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
    INSERT INTO user_login_audit
        (username, session_id, login_time, action_type, ip_address, hostname)
    VALUES (
        SYS_CONTEXT('USERENV', 'SESSION_USER'),   -- database username
        SYS_CONTEXT('USERENV', 'SESSIONID'),      -- session (audit) ID
        SYSTIMESTAMP,
        'LOGIN',
        SYS_CONTEXT('USERENV', 'IP_ADDRESS'),     -- client IP address
        SYS_CONTEXT('USERENV', 'HOST')            -- client host name
    );
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;   -- deliberately silent: auditing must never block a login
END trg_user_login;
/


/* ============================================================
   STEP 3 (TASKS 3 + 4): BEFORE LOGOFF TRIGGER
   Updates the open LOGIN row of THIS session.
   MAX(audit_id) picks the latest one, in case the same session id
   appears more than once (e.g. SYS sessions share one id).
   ============================================================ */
CREATE OR REPLACE TRIGGER trg_user_logout
BEFORE LOGOFF ON DATABASE
DECLARE
    PRAGMA AUTONOMOUS_TRANSACTION;

    v_user       VARCHAR2(128) := SYS_CONTEXT('USERENV', 'SESSION_USER');
    v_session_id NUMBER        := SYS_CONTEXT('USERENV', 'SESSIONID');
BEGIN
    UPDATE user_login_audit
    SET logout_time = SYSTIMESTAMP,
        action_type = 'LOGOUT'
    WHERE audit_id = (
        SELECT MAX(audit_id)
        FROM user_login_audit
        WHERE session_id  = v_session_id
          AND username    = v_user
          AND logout_time IS NULL
    );
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;   -- deliberately silent: auditing must never block a logout
END trg_user_logout;
/


/* ============================================================
   STEP 4 (TASK 6): ARE BOTH TRIGGERS CREATED AND ENABLED?
   Expect 2 rows, both STATUS = ENABLED.
   ============================================================ */
SELECT trigger_name,
       trigger_type,        -- AFTER EVENT / BEFORE EVENT
       triggering_event,    -- LOGON / LOGOFF
       base_object_type,    -- DATABASE
       status
FROM user_triggers
WHERE trigger_name IN ('TRG_USER_LOGIN', 'TRG_USER_LOGOUT')
ORDER BY trigger_name;

-- Also confirm they compiled without errors (status VALID)
SELECT object_name, object_type, status
FROM user_objects
WHERE object_name IN ('TRG_USER_LOGIN', 'TRG_USER_LOGOUT');


/* ============================================================
   STEP 5: TEST
   1. Open a NEW connection (SQL Developer / SQL*Plus), e.g.:
          sqlplus hr/hr@localhost:1521/XEPDB1
      -> a LOGIN row appears.
   2. Type EXIT (or disconnect)
      -> the same row gets LOGOUT_TIME and ACTION_TYPE = 'LOGOUT'.
   3. Run the queries below from the SYSTEM session.
   ============================================================ */


/* ============================================================
   STEP 6 (TASK 5): ALL LOGIN / LOGOUT RECORDS
   ============================================================ */
SELECT audit_id,
       username,
       session_id,
       TO_CHAR(login_time,  'DD-MON-YYYY HH24:MI:SS') AS login_time,
       TO_CHAR(logout_time, 'DD-MON-YYYY HH24:MI:SS') AS logout_time,
       action_type,
       NVL(ip_address, 'LOCAL') AS ip_address,
       hostname
FROM user_login_audit
ORDER BY audit_id DESC;


/* ============================================================
   STEP 7 (EXTRA REPORTS)
   ============================================================ */

-- 7.1 Session duration (completed sessions)
SELECT username,
       session_id,
       login_time,
       logout_time,
       logout_time - login_time AS session_duration   -- INTERVAL DAY TO SECOND
FROM user_login_audit
WHERE logout_time IS NOT NULL
ORDER BY login_time DESC;

-- 7.2 Sessions still open (or ended abnormally)
SELECT username, session_id, login_time, ip_address, hostname
FROM user_login_audit
WHERE logout_time IS NULL
ORDER BY login_time DESC;

-- 7.3 Logins per user per day
SELECT username,
       TRUNC(login_time) AS login_day,
       COUNT(*)          AS number_of_logins
FROM user_login_audit
GROUP BY username, TRUNC(login_time)
ORDER BY login_day DESC, number_of_logins DESC;


