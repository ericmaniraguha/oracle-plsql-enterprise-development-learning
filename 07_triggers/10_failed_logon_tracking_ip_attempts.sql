/* ============================================================
   KEY POINTS
   - Wrong password => ORA-01017 => AFTER SERVERERROR trigger, NOT LOGON.
   - Always filter with ORA_IS_SERVERERROR(...) at the top: the trigger
     fires for errors in every session.
   - Use PRAGMA AUTONOMOUS_TRANSACTION + COMMIT to keep the log rows.
   - SYS_CONTEXT('USERENV', ...) gives IP_ADDRESS, HOST, OS_USER, MODULE.
   - MERGE = "insert the first time, update afterwards" in one statement.
   - Locking accounts is a PROFILE's job (FAILED_LOGIN_ATTEMPTS).
   ============================================================ */
