/* ============================================================
   TITLE: Tracking Failed Login Attempts (Wrong Password)
          with IP Address, Host and Number of Attempts

   QUESTION:
   Security wants to know who is trying to log in with a wrong
   username/password. For every failed attempt record:
     - the username that was tried
     - the IP address, client host name and OS user
     - the date/time of the attempt
   and keep a running COUNT of attempts per (username, IP address),
   so that suspicious users / machines are easy to spot.

   HOW IT WORKS:
   A wrong password does NOT fire a LOGON trigger (the session never
   logs on). Instead Oracle raises
       ORA-01017: invalid username/password; logon denied
   and a database-level  AFTER SERVERERROR  trigger can catch it.
   ORA_IS_SERVERERROR(1017) tells us the error is a failed login.

   REQUIREMENTS:
   - Run as SYSTEM (or a user with ADMINISTER DATABASE TRIGGER and
     CREATE TABLE / CREATE TRIGGER). The tables live in that schema.
   - Works on Oracle 11g, 12c, 18c, 19c, 21c, 23ai.

   NOTE: To actually LOCK an account after N failures, use a PROFILE
   (FAILED_LOGIN_ATTEMPTS) - see Step 7. The trigger is for reporting.
   ============================================================ */


/* ============================================================
   STEP 0: CLEAN START (trigger first, then tables)
   ============================================================ */
BEGIN
    EXECUTE IMMEDIATE 'DROP TRIGGER trg_failed_logon';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -4080 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE failed_login_log PURGE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE failed_login_summary PURGE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/


/* ============================================================
   STEP 1: DETAIL TABLE - one row per failed attempt
   ============================================================ */
CREATE TABLE failed_login_log (
    log_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempted_user  VARCHAR2(128),
    ip_address      VARCHAR2(50),
    host_name       VARCHAR2(256),
    os_user         VARCHAR2(256),
    program_name    VARCHAR2(256),
    error_code      NUMBER,
    attempt_time    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);


/* ============================================================
   STEP 2: SUMMARY TABLE - one row per (username, IP address)
   ============================================================ */
CREATE TABLE failed_login_summary (
    attempted_user  VARCHAR2(128),
    ip_address      VARCHAR2(50),
    attempt_count   NUMBER       DEFAULT 0 NOT NULL,
    first_attempt   TIMESTAMP,
    last_attempt    TIMESTAMP,
    CONSTRAINT failed_login_summary_pk PRIMARY KEY (attempted_user, ip_address)
);


/* ============================================================
   STEP 3: THE TRIGGER

   - AFTER SERVERERROR ON DATABASE fires for (almost) every error in
     every session, so the first thing we do is test for ORA-01017
     and leave immediately otherwise.
   - PRAGMA AUTONOMOUS_TRANSACTION: the failing connection never
     commits anything, so the log rows must be committed in their
     own independent transaction.
   - Attempted username: Oracle has no logged-on user yet.
     AUTHENTICATED_IDENTITY usually holds the name that was typed;
     ORA_LOGIN_USER is a fallback. If both are empty -> 'UNKNOWN'.
   - IP_ADDRESS is NULL for a local (non-network) connection, so it
     is stored as 'LOCAL'.
   - WHEN OTHERS -> ROLLBACK: a problem in the logging must never
     add a second error to the user's login.
   ============================================================ */
CREATE OR REPLACE TRIGGER trg_failed_logon
AFTER SERVERERROR ON DATABASE
DECLARE
    PRAGMA AUTONOMOUS_TRANSACTION;

    v_user    VARCHAR2(128);
    v_ip      VARCHAR2(50);
    v_host    VARCHAR2(256);
    v_os_user VARCHAR2(256);
    v_program VARCHAR2(256);
BEGIN
    IF ORA_IS_SERVERERROR(1017) THEN

        v_user    := UPPER(NVL(SYS_CONTEXT('USERENV', 'AUTHENTICATED_IDENTITY'),
                               NVL(ORA_LOGIN_USER, 'UNKNOWN')));
        v_ip      := NVL(SYS_CONTEXT('USERENV', 'IP_ADDRESS'), 'LOCAL');
        v_host    := SYS_CONTEXT('USERENV', 'HOST');
        v_os_user := SYS_CONTEXT('USERENV', 'OS_USER');
        v_program := SYS_CONTEXT('USERENV', 'MODULE');

        -- 1) detail row
        INSERT INTO failed_login_log
            (attempted_user, ip_address, host_name, os_user, program_name, error_code)
        VALUES
            (v_user, v_ip, v_host, v_os_user, v_program, 1017);

        -- 2) running counter per (user, IP): insert first time, add 1 after
        MERGE INTO failed_login_summary s
        USING (SELECT v_user AS attempted_user, v_ip AS ip_address FROM dual) src
        ON (s.attempted_user = src.attempted_user AND s.ip_address = src.ip_address)
        WHEN MATCHED THEN
            UPDATE SET s.attempt_count = s.attempt_count + 1,
                       s.last_attempt  = SYSTIMESTAMP
        WHEN NOT MATCHED THEN
            INSERT (attempted_user, ip_address, attempt_count, first_attempt, last_attempt)
            VALUES (src.attempted_user, src.ip_address, 1, SYSTIMESTAMP, SYSTIMESTAMP);

        COMMIT;   -- required in an autonomous transaction
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK; -- deliberately silent: logging must never disturb a login
END trg_failed_logon;
/


/* ============================================================
   STEP 4: TEST
   From a command prompt, try to connect with a WRONG password
   3 times (any existing or non-existing user), e.g.:

       sqlplus hr/wrongpass@localhost:1521/XEPDB1
       sqlplus hr/wrongpass2@localhost:1521/XEPDB1
       sqlplus hacker/1234@localhost:1521/XEPDB1

   (In SQL Developer: create a connection with a wrong password and
    click "Test" a few times.)
   Each attempt shows ORA-01017 to the user and is logged here.
   ============================================================ */


/* ============================================================
   STEP 5: REPORTS
   ============================================================ */

-- 5.1 Every failed attempt, newest first
SELECT log_id,
       attempted_user,
       ip_address,
       host_name,
       os_user,
       program_name,
       TO_CHAR(attempt_time, 'DD-MON-YYYY HH24:MI:SS') AS attempt_time
FROM failed_login_log
ORDER BY attempt_time DESC;

-- 5.2 How many attempts per user and IP address
SELECT attempted_user,
       ip_address,
       attempt_count,
       TO_CHAR(first_attempt, 'DD-MON-YYYY HH24:MI:SS') AS first_attempt,
       TO_CHAR(last_attempt,  'DD-MON-YYYY HH24:MI:SS') AS last_attempt
FROM failed_login_summary
ORDER BY attempt_count DESC;

-- 5.3 Suspicious: 3 or more failures in the last 30 minutes
SELECT attempted_user,
       ip_address,
       COUNT(*)          AS attempts_last_30_min,
       MAX(attempt_time) AS last_attempt
FROM failed_login_log
WHERE attempt_time >= SYSTIMESTAMP - INTERVAL '30' MINUTE
GROUP BY attempted_user, ip_address
HAVING COUNT(*) >= 3
ORDER BY attempts_last_30_min DESC;

-- 5.4 One IP address trying MANY different usernames (password spraying)
SELECT ip_address,
       COUNT(DISTINCT attempted_user) AS different_users_tried,
       COUNT(*)                        AS total_attempts
FROM failed_login_log
GROUP BY ip_address
HAVING COUNT(DISTINCT attempted_user) > 1
ORDER BY different_users_tried DESC;


/* ============================================================
   STEP 6: IS THE TRIGGER ENABLED?
   ============================================================ */
SELECT trigger_name, trigger_type, triggering_event, base_object_type, status
FROM user_triggers
WHERE trigger_name = 'TRG_FAILED_LOGON';

