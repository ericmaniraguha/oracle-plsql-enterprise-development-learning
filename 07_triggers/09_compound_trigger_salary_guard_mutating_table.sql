/* ============================================================
   KEY POINTS - COMPOUND TRIGGERS
   - Syntax: FOR <events> ON <table> COMPOUND TRIGGER ... END;
   - Up to 4 sections: BEFORE STATEMENT, BEFORE EACH ROW,
     AFTER EACH ROW, AFTER STATEMENT (use only the ones you need).
   - Variables declared at the top are shared by all sections and
     reset for every triggering statement.
   - :NEW / :OLD are available ONLY in the EACH ROW sections.
   - Typical uses: avoiding ORA-04091 (mutating table), collecting rows
     and bulk-inserting them, counting affected rows.
   - Only for DML on a table or view; not for system events (LOGON...).
   ============================================================ */
