-- Averages before the test (department 60 in the standard HR data = 5760)
SELECT department_id,
       ROUND(AVG(salary), 2)     AS avg_salary,
       ROUND(AVG(salary) * 2, 2) AS max_allowed
FROM employees
WHERE department_id IN (60, 90)
GROUP BY department_id;

-- TEST A (allowed): 5% raise for department 60 -> 5 rows logged, no error
UPDATE employees
SET salary = salary * 1.05
WHERE department_id = 60;

SELECT * FROM emp_salary_change_log ORDER BY log_id;

-- TEST B (denied): 20000 is more than 2 x the department 60 average
-- Expected: ORA-20010: Salary 20000 for employee 104 exceeds 2 x department 60 average (...)
UPDATE employees
SET salary = 20000
WHERE employee_id = 104;

-- TEST C (allowed): a decrease is never blocked
UPDATE employees
SET salary = salary - 100
WHERE employee_id = 104;

SELECT * FROM emp_salary_change_log ORDER BY log_id;

-- Demo only: undo the salary changes and their log rows
ROLLBACK;


