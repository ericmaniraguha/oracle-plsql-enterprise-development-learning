/* ============================================================
   STEP 3: THE COMPOUND TRIGGER
   ============================================================ */
CREATE OR REPLACE TRIGGER trg_emp_salary_guard
FOR UPDATE OF salary ON employees
COMPOUND TRIGGER

    /* ---------- Declarations shared by all timing points ----------
       They live only for ONE triggering statement and are
       re-initialized for the next one.                            */
    c_max_factor CONSTANT NUMBER := 2;     -- max = 2 x department average

    -- Department averages, indexed by department_id
    TYPE t_avg_tab IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    g_dept_avg t_avg_tab;

    -- Changes waiting to be written in AFTER STATEMENT
    TYPE t_change_rec IS RECORD (
        employee_id   employees.employee_id%TYPE,
        department_id employees.department_id%TYPE,
        old_salary    employees.salary%TYPE,
        new_salary    employees.salary%TYPE
    );
    TYPE t_change_tab IS TABLE OF t_change_rec INDEX BY PLS_INTEGER;
    g_changes t_change_tab;

    /* ========================================================
       BEFORE STATEMENT: cache the averages (table not mutating yet)
       ======================================================== */
    BEFORE STATEMENT IS
    BEGIN
        FOR r IN (
            SELECT department_id, AVG(salary) AS avg_sal
            FROM employees
            WHERE department_id IS NOT NULL
            GROUP BY department_id
        ) LOOP
            g_dept_avg(r.department_id) := r.avg_sal;
        END LOOP;
    END BEFORE STATEMENT;

    /* ========================================================
       BEFORE EACH ROW: validate using the cache (no SQL here)
       Only raises are checked; a salary decrease is always allowed.
       ======================================================== */
    BEFORE EACH ROW IS
    BEGIN
        IF :NEW.salary > :OLD.salary
           AND :NEW.department_id IS NOT NULL
           AND g_dept_avg.EXISTS(:NEW.department_id)
           AND :NEW.salary > g_dept_avg(:NEW.department_id) * c_max_factor
        THEN
            RAISE_APPLICATION_ERROR(
                -20010,
                'Salary ' || :NEW.salary || ' for employee ' || :NEW.employee_id
                || ' exceeds ' || c_max_factor || ' x department '
                || :NEW.department_id || ' average ('
                || ROUND(g_dept_avg(:NEW.department_id), 2) || ').'
            );
        END IF;
    END BEFORE EACH ROW;

    /* ========================================================
       AFTER EACH ROW: remember the change (memory only)
       ======================================================== */
    AFTER EACH ROW IS
        i PLS_INTEGER;
    BEGIN
        -- DECODE treats NULL = NULL as equal: skip rows whose salary did not change
        IF DECODE(:OLD.salary, :NEW.salary, 0, 1) = 1 THEN
            i := g_changes.COUNT + 1;
            g_changes(i).employee_id   := :NEW.employee_id;
            g_changes(i).department_id := :NEW.department_id;
            g_changes(i).old_salary    := :OLD.salary;
            g_changes(i).new_salary    := :NEW.salary;
        END IF;
    END AFTER EACH ROW;

    /* ========================================================
       AFTER STATEMENT: ONE bulk insert for the whole statement
       ======================================================== */
    AFTER STATEMENT IS
    BEGIN
        FORALL i IN 1 .. g_changes.COUNT
            INSERT INTO emp_salary_change_log
                (employee_id, department_id, old_salary, new_salary, changed_by)
            VALUES
                (g_changes(i).employee_id,
                 g_changes(i).department_id,
                 g_changes(i).old_salary,
                 g_changes(i).new_salary,
                 SYS_CONTEXT('USERENV', 'SESSION_USER'));
    END AFTER STATEMENT;

END trg_emp_salary_guard;
/


