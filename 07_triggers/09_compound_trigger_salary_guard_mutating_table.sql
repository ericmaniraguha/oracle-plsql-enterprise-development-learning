/* ============================================================
   TITLE: Compound Trigger (Example 2) - Salary Guard that Avoids
          the Mutating Table Error (ORA-04091) + Bulk Change Log

   QUESTION:
   HR wants two rules on every salary UPDATE of EMPLOYEES:
   1. A salary RAISE must not push an employee above 2 x the average
      salary of his/her department (average taken BEFORE the update).
   2. Every salary change must be written to EMP_SALARY_CHANGE_LOG
      (employee, old salary, new salary, who, when).

   WHY A NORMAL ROW-LEVEL TRIGGER FAILS:
   Rule 1 needs   SELECT AVG(salary) FROM employees ...
   inside a FOR EACH ROW trigger on EMPLOYEES. Oracle refuses this:
       ORA-04091: table EMPLOYEES is mutating, trigger/function may not see it
   because the table is half-way through being changed.

   HOW THE COMPOUND TRIGGER SOLVES IT:
   One trigger, four timing points, SHARED variables:

     BEFORE STATEMENT  -> read the department averages ONCE (table is
                          not mutating yet) and cache them in a collection
     BEFORE EACH ROW   -> check :NEW.salary against the cached average
                          (no SQL on EMPLOYEES -> no ORA-04091)
     AFTER EACH ROW    -> remember the change in a collection (memory only)
     AFTER STATEMENT   -> write all remembered changes with ONE FORALL
                          (bulk insert, much faster than row-by-row)

   Compare with 04_CompoundTriggerDMLAuditTrigger_Tracking_Emp_table.sql
   (Example 1), which only counted rows.
   ============================================================ */


/* ============================================================
   STEP 1: CHANGE LOG TABLE
   Drop the trigger FIRST, then the table (a trigger on EMPLOYEES that
   points to a missing table becomes INVALID and breaks every UPDATE).
   ============================================================ */
BEGIN
    EXECUTE IMMEDIATE 'DROP TRIGGER trg_emp_salary_guard';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -4080 THEN   -- ORA-04080: trigger does not exist
            RAISE;
        END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE emp_salary_change_log PURGE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN    -- ORA-00942: table does not exist
            RAISE;
        END IF;
END;
/

CREATE TABLE emp_salary_change_log (
    log_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   NUMBER(6),
    department_id NUMBER(4),
    old_salary    NUMBER(8,2),
    new_salary    NUMBER(8,2),
    changed_by    VARCHAR2(128),
    changed_at    TIMESTAMP DEFAULT SYSTIMESTAMP
);


