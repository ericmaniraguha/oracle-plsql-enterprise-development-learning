--We can create a generic audit table to store statement-level triggers:
--
-- IMPROVED: user name columns are VARCHAR2(128). Since Oracle 12.2, user names
-- can be up to 128 characters, so VARCHAR2(30) could raise ORA-12899 inside
-- the trigger and make the audited INSERT/UPDATE/DELETE fail.
-- Note: the lesson scripts 04-07 in this folder drop and re-create
-- EMPLOYEES_AUDIT with their own columns.

CREATE TABLE employees_audit (
    audit_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type    VARCHAR2(50),
    action_date    DATE,
    affected_table VARCHAR2(128),
    total_rows     NUMBER,
    db_user        VARCHAR2(128),
    os_user        VARCHAR2(128),
    client_ip      VARCHAR2(50),
    session_id     VARCHAR2(50)
);
