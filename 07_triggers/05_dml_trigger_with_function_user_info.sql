-- ============================================================================================
-- ROW-LEVEL DML AUDIT TRIGGER THAT CALLS A FUNCTION
--
-- OPTIMIZED: the trigger had three almost identical INSERT statements (one per
-- operation). It now works out the action type once and runs ONE INSERT:
-- less code to maintain, and impossible for the three copies to drift apart.
--
-- FIXED:
-- - The test inserted employee 101, who already exists (Neena Kochhar), so the
--   INSERT failed with ORA-00001, and the test then tried to DELETE employee
--   101. The test now uses a new ID (999) and ends with ROLLBACK.
-- - Step 0 removes audit triggers left by the other lessons (they become
--   INVALID when EMPLOYEES_AUDIT is re-created, and every DML on EMPLOYEES
--   then fails with ORA-04098).
-- - db_user / os_user are VARCHAR2(128). Longer names (e.g. DOMAIN\user) used
--   to overflow VARCHAR2(30) and make the audited DML fail.
-- ============================================================================================

-- 0. Remove audit triggers left by the other lessons in this folder
BEGIN
    FOR t IN (
        SELECT trigger_name
        FROM user_triggers
        WHERE trigger_name IN ('EMP_AUDIT_TRG', 'EMP_AUDIT_TRIGGER', 'EMP_AUDIT_TAX_TRIGGER')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TRIGGER ' || DBMS_ASSERT.ENQUOTE_NAME(t.trigger_name);
    END LOOP;
END;
/

-- 1. Drop Audit Table if exists
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE employees_audit CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN  -- ignore table not exists
            RAISE;
        END IF;
END;
/
-- ============================================================================================

-- 2. Create function to get client IP
-- (Calling SYS_CONTEXT directly in the trigger would be slightly faster; the
--  function is here to show how a trigger can call reusable PL/SQL.)
CREATE OR REPLACE FUNCTION get_client_info
RETURN VARCHAR2
IS
BEGIN
    RETURN SYS_CONTEXT('USERENV','IP_ADDRESS');
END;
/
-- Test the function
SELECT get_client_info() AS client_ip FROM dual;
-- ============================================================================================

-- 3. Create Audit Table
CREATE TABLE employees_audit (
    audit_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type    VARCHAR2(20),
    action_date    DATE,
    affected_table VARCHAR2(128),
    total_rows     NUMBER,
    db_user        VARCHAR2(128),
    os_user        VARCHAR2(128),
    client_ip      VARCHAR2(50),
    session_id     VARCHAR2(50)
);
-- ============================================================================================

-- 4. Create a single trigger for all DML operations
CREATE OR REPLACE TRIGGER emp_audit_trigger
AFTER INSERT OR UPDATE OR DELETE ON employees
FOR EACH ROW
DECLARE
    v_action employees_audit.action_type%TYPE;
BEGIN
    -- Work out the operation once (PL/SQL predicates INSERTING / UPDATING)
    v_action := CASE
                    WHEN INSERTING THEN 'INSERT'
                    WHEN UPDATING  THEN 'UPDATE'
                    ELSE                'DELETE'
                END;

    -- One INSERT for all three operations
    INSERT INTO employees_audit (
        action_type,
        action_date,
        affected_table,
        total_rows,
        db_user,
        os_user,
        client_ip,
        session_id
    ) VALUES (
        v_action,
        SYSDATE,
        'EMPLOYEES',
        1,  -- row-level trigger: one row per firing
        SYS_CONTEXT('USERENV','SESSION_USER'),
        SYS_CONTEXT('USERENV','OS_USER'),
        get_client_info(),
        SYS_CONTEXT('USERENV','SESSIONID')
    );
END;
/
-- ============================================================================================

