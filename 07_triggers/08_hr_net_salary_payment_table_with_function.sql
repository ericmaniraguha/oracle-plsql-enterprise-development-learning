/* =========================================================
   EXAM QUESTION
   ---------------------------------------------------------
   Design a PL/SQL solution that automatically calculates
   the Net Salary of an employee whenever HR inserts or
   updates an employee record.

   Requirements:
   1. Create EMPLOYEES table with given attributes.
   2. Create EMPLOYEE_PAYMENT table to store salary records.
   3. Create a function to calculate Net Salary.
   4. Create a trigger that:
      - Automatically calculates Net Salary
      - Validates that salary processing is only allowed in APRIL
        (based on CREATED_AT date)
      - Inserts payroll information into payment table
   ========================================================= */

/* =========================================================
   EMPLOYEE PAYROLL SYSTEM (PL/SQL FULL SOLUTION)
   ---------------------------------------------------------
   FEATURES:
   1. Employees table
   2. Payroll/payment table
   3. Function to calculate Net Salary
   4. Trigger:
      - Validates APRIL only
      - Calculates Net Salary
      - Inserts payroll record automatically
   5. Test cases + queries

   WHAT CHANGED AND WHY
   ---------------------------------------------------------
   The old script altered the shared HR EMPLOYEES table and put the trigger
   on it. That broke the whole course:
   - HR EMPLOYEES has no CREATED_AT column, so TRG_EMPLOYEE_SALARY compiled
     INVALID, and from then on EVERY insert/update/delete on EMPLOYEES (in
     every other lesson) failed with ORA-04098.
   - Even if it compiled, the "APRIL only" rule would have blocked every
     salary update in the other lessons for 11 months of the year.
   - The test INSERT used columns HR EMPLOYEES does not have (ADDRESS,
     ROLE_ID, STATUS, CREATED_AT) and no EMPLOYEE_ID.
   - The payment row was inserted in a BEFORE INSERT trigger. At that moment
     the employee row does not exist yet, so the foreign key on
     EMPLOYEE_PAYMENT failed (ORA-02291).
   - Every update of ANY column created another payment row.

   Fixes:
   - The exam's own table is now PAYROLL_EMPLOYEES (the exam's EMPLOYEES
     definition), so HR EMPLOYEES and the other lessons are untouched.
   - A COMPOUND trigger: BEFORE EACH ROW validates and calculates (it may
     change :NEW), AFTER EACH ROW inserts the payment (the employee row
     exists by then, so the foreign key is satisfied).
   - The trigger fires on INSERT and on UPDATE OF SALARY only.
   - The foreign key column on EMPLOYEE_PAYMENT is indexed.
   ========================================================= */


/* ================================
   STEP 0: CLEAN UP
================================ */
-- Remove the invalid trigger the OLD version of this script left on HR EMPLOYEES.
-- (The old script also added a NET_SALARY column to HR EMPLOYEES. It is harmless;
--  drop it yourself if you like:  ALTER TABLE employees DROP COLUMN net_salary;)
BEGIN
    FOR t IN (
        SELECT trigger_name
        FROM user_triggers
        WHERE trigger_name = 'TRG_EMPLOYEE_SALARY'
          AND table_name   = 'EMPLOYEES'
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TRIGGER ' || DBMS_ASSERT.ENQUOTE_NAME(t.trigger_name);
    END LOOP;
END;
/

-- Drop this lesson's own tables so the script can be re-run (child table first)
DECLARE
    PROCEDURE drop_table_if_exists(p_table VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE 'DROP TABLE ' || DBMS_ASSERT.SIMPLE_SQL_NAME(p_table) || ' CASCADE CONSTRAINTS';
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -942 THEN   -- -942 = table does not exist
                RAISE;
            END IF;
    END;
BEGIN
    drop_table_if_exists('EMPLOYEE_PAYMENT');
    drop_table_if_exists('PAYROLL_EMPLOYEES');
END;
/


/* ================================
   STEP 1: EMPLOYEES TABLE (named PAYROLL_EMPLOYEES)
================================ */
CREATE TABLE PAYROLL_EMPLOYEES (
    EMPLOYEE_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME      VARCHAR2(50),
    LAST_NAME       VARCHAR2(50),
    EMAIL           VARCHAR2(100),
    PHONE_NUMBER    VARCHAR2(20),
    ADDRESS         VARCHAR2(200),
    HIRE_DATE       DATE,
    DEPARTMENT_ID   NUMBER,
    ROLE_ID         NUMBER,
    SALARY          NUMBER(10,2),
    STATUS          VARCHAR2(20),
    CREATED_AT      DATE,
    UPDATED_AT      DATE,
    NET_SALARY      NUMBER(10,2)
);


/* ================================
   STEP 2: EMPLOYEE PAYMENT TABLE
================================ */
CREATE TABLE EMPLOYEE_PAYMENT (
    PAYMENT_ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID     NUMBER NOT NULL,
    FULL_NAME       VARCHAR2(120),
    DEPARTMENT_ID   NUMBER,
    GROSS_SALARY    NUMBER(10,2),
    NET_SALARY      NUMBER(10,2),
    PAYMENT_DATE    DATE,
    CONSTRAINT FK_EMP_PAYMENT
        FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES PAYROLL_EMPLOYEES (EMPLOYEE_ID)
);

-- Index the foreign key: payments are looked up by employee, and deleting an
-- employee would otherwise full-scan (and lock) the whole payment table.
CREATE INDEX EMP_PAYMENT_EMP_IX ON EMPLOYEE_PAYMENT (EMPLOYEE_ID);


/* ================================
   STEP 3: FUNCTION
   CALCULATE NET SALARY
================================ */
CREATE OR REPLACE FUNCTION CALC_NET_SALARY (
    p_salary IN NUMBER
) RETURN NUMBER
DETERMINISTIC   -- same gross salary always gives the same net salary
IS
    c_tax_rate     CONSTANT NUMBER := 0.15;   -- 15% TAX
    c_pension_rate CONSTANT NUMBER := 0.05;   -- 5% PENSION
BEGIN
    -- NET SALARY = gross - (tax + pension)
    RETURN p_salary - (p_salary * c_tax_rate + p_salary * c_pension_rate);
END;
/


/* ================================
   STEP 4: TRIGGER
   AUTO CALCULATION + VALIDATION + REPORT
================================ */
CREATE OR REPLACE TRIGGER TRG_PAYROLL_EMPLOYEE_SALARY
FOR INSERT OR UPDATE OF SALARY ON PAYROLL_EMPLOYEES
COMPOUND TRIGGER

    /* ----------------------------------------
       BEFORE EACH ROW: validate and calculate.
       Only a BEFORE row trigger may change :NEW values.
    ---------------------------------------- */
    BEFORE EACH ROW IS
    BEGIN
        -- ENSURE CREATED_AT HAS VALUE
        IF :NEW.CREATED_AT IS NULL THEN
            :NEW.CREATED_AT := SYSDATE;
        END IF;

        -- VALIDATE: ONLY APRIL IS ALLOWED
        IF EXTRACT(MONTH FROM :NEW.CREATED_AT) <> 4 THEN
            RAISE_APPLICATION_ERROR(-20001,
                'Salary processing is only allowed in APRIL.');
        END IF;

        -- CALCULATE NET SALARY USING FUNCTION (stored so it can be reported)
        :NEW.NET_SALARY := CALC_NET_SALARY(:NEW.SALARY);

        IF UPDATING THEN
            :NEW.UPDATED_AT := SYSDATE;
        END IF;
    END BEFORE EACH ROW;

    /* ----------------------------------------
       AFTER EACH ROW: write the payment record.
       The employee row now exists, so the foreign key is satisfied.
    ---------------------------------------- */
    AFTER EACH ROW IS
    BEGIN
        INSERT INTO EMPLOYEE_PAYMENT (
            EMPLOYEE_ID,
            FULL_NAME,
            DEPARTMENT_ID,
            GROSS_SALARY,
            NET_SALARY,
            PAYMENT_DATE
        )
        VALUES (
            :NEW.EMPLOYEE_ID,
            :NEW.FIRST_NAME || ' ' || :NEW.LAST_NAME,
            :NEW.DEPARTMENT_ID,
            :NEW.SALARY,
            :NEW.NET_SALARY,
            SYSDATE
        );
    END AFTER EACH ROW;

END TRG_PAYROLL_EMPLOYEE_SALARY;
/


