/* ============================================================
   STATEMENT-LEVEL DML AUDIT TRIGGER ON EMPLOYEES

   FIXED: the old trigger stored SQL%ROWCOUNT as "affected_rows", but the
   column was ALWAYS NULL. Inside a trigger, SQL%ROWCOUNT describes the
   last SQL statement run BY THE TRIGGER (none yet), not the INSERT /
   UPDATE / DELETE that fired it. A statement-level trigger simply cannot
   see how many rows were affected. To count them, use the compound trigger
   in 04_CompoundTriggerDMLAuditTrigger_Tracking_Emp_table.sql.
   This version leaves affected_rows NULL on purpose and says so.

   Other fixes: Step 0 removes leftover audit triggers of the other lessons
   (a leftover trigger becomes INVALID when EMPLOYEES_AUDIT is re-created
   and then every DML on EMPLOYEES fails with ORA-04098); the test INSERT no
   longer lists the optional BONUS column; db_user is VARCHAR2(128); the
   demo ends with ROLLBACK.
   ============================================================ */

/* ============================================================
   STEP 0: REMOVE AUDIT TRIGGERS LEFT BY THE OTHER LESSONS
   ============================================================ */
BEGIN
    FOR t IN (
        SELECT trigger_name
        FROM user_triggers
        WHERE trigger_name IN ('EMP_AUDIT_TRG', 'EMP_AUDIT_TRIGGER', 'EMP_AUDIT_TAX_TRIGGER')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TRIGGER ' || DBMS_ASSERT.ENQUOTE_NAME(t.trigger_name);
    END LOOP;
END;
/

/* ============================================================
   STEP 1: DROP AUDIT TABLE IF IT EXISTS
   - This block attempts to drop the table.
   - If the table does not exist, it ignores the error.
   ============================================================ */
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE employees_audit CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN -- Ignore "table does not exist" error
            RAISE;
        END IF;
END;
/

/* ============================================================
   STEP 2: CREATE AUDIT TABLE
   - This table will store all audit logs for DML operations.
   ============================================================ */
CREATE TABLE employees_audit(
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type VARCHAR2(50),     -- Type of operation (INSERT, UPDATE, DELETE)
    action_date DATE,             -- Date when action occurred
    affected_rows NUMBER,         -- Not knowable in a statement trigger: stays NULL
    db_user VARCHAR2(128),        -- Database user who performed the action
    session_id VARCHAR2(50)       -- Session ID of the user
);

/* ============================================================
   STEP 3: CREATE TRIGGER
   - This is a statement-level trigger (no FOR EACH ROW).
   - It fires ONCE per INSERT, UPDATE, or DELETE statement on EMPLOYEES.
   ============================================================ */
CREATE OR REPLACE TRIGGER emp_audit_trg
AFTER INSERT OR UPDATE OR DELETE ON employees
DECLARE
    v_action VARCHAR2(50); -- Stores action type
BEGIN
    /* Determine the type of DML operation.
       INSERTING / UPDATING / DELETING are PL/SQL predicates, so they are
       evaluated here in PL/SQL, not inside the INSERT statement. */
    v_action := CASE
                    WHEN INSERTING THEN 'INSERT STATEMENT'
                    WHEN UPDATING  THEN 'UPDATE STATEMENT'
                    ELSE                'DELETE STATEMENT'
                END;

    /* Insert audit record */
    INSERT INTO employees_audit (
        action_type,
        action_date,
        affected_rows,
        db_user,
        session_id
    )
    VALUES(
        v_action,
        SYSDATE,
        NULL,   -- see header: a statement trigger cannot count affected rows
        SYS_CONTEXT('USERENV','SESSION_USER'),
        SYS_CONTEXT('USERENV','SESSIONID')
    );
END;
/

/* ============================================================
   STEP 4: TEST THE TRIGGER
   - Perform an INSERT operation
   ============================================================ */
INSERT INTO EMPLOYEES (
    EMPLOYEE_ID, FIRST_NAME, LAST_NAME, EMAIL, PHONE_NUMBER,
