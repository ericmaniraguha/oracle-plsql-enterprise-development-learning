/*
STATEMENT-LEVEL trigger: ONE audit row per UPDATE statement, no matter how
many rows the statement changes (even zero).
(Compare with 01_trigger_row_level_salary_logs.sql: one row per employee.)

FIXED: this file used to be an exact copy of the row-level script
(it had FOR EACH ROW), so it never demonstrated a statement-level trigger.

Key differences from a row-level trigger:
- No "FOR EACH ROW" clause.
- :OLD and :NEW are NOT available (there is no single "current row").
- It fires once, so it is much cheaper when a statement touches many rows.
- Use it to record THAT a change happened (who, when, which operation);
  use a row-level trigger to record WHAT changed in each row.

It writes to its own table (salary_statement_audit) so it does not clash with
the salary_audit table of the row-level lesson.
*/

-- 1. Drop previous audit table if exists (optional cleanup)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE salary_statement_audit';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN -- -942 = table does not exist
            RAISE;
        END IF;
END;
/

-- 2. Create audit table
CREATE TABLE salary_statement_audit (
    audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type VARCHAR2(10),
    changed_by  VARCHAR2(128) DEFAULT USER,
    change_date DATE          DEFAULT SYSDATE
);

-- 3. Create the statement-level trigger (note: no FOR EACH ROW)
CREATE OR REPLACE TRIGGER log_salary_statements
AFTER UPDATE OF salary ON employees
BEGIN
    INSERT INTO salary_statement_audit (action_type)
    VALUES ('UPDATE');
END;
/

-- 4. One UPDATE that changes 5 rows (department 60)...
UPDATE employees
SET salary = salary + 500
WHERE department_id = 60;

-- 5. ...produces exactly ONE audit row
SELECT * FROM salary_statement_audit ORDER BY audit_id;

-- 6. Demo only: undo the raise (and the audit row). Use COMMIT to keep them.
ROLLBACK;
