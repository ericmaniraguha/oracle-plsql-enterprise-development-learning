/* ============================================================
   STEP 5: VERIFY AUDIT RESULTS
   Expect 3 rows: INSERT (1 row), UPDATE (3 rows), DELETE (1 row)
   ============================================================ */
SELECT * FROM employees_audit ORDER BY audit_id;

